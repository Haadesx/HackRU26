"""MedCheck frozen v1 contract models (pydantic v2).

Owner: ORCHESTRATOR (Apollo). Mirror of contracts/v1/scan_response.schema.json.
Workers: import these models; request changes via Bus, do not edit this file.
"""
from __future__ import annotations

from typing import Any, Dict, List, Optional

from pydantic import BaseModel, ConfigDict, Field

CONTRACT_VERSION = "1.3.0"

SAFETY_DISCLAIMER = (
    "Informational only; not medical advice. "
    "Verify with a pharmacist or prescriber."
)


class BBox(BaseModel):
    model_config = ConfigDict(extra="forbid")
    x: float = Field(ge=0, le=1)
    y: float = Field(ge=0, le=1)
    w: float = Field(ge=0, le=1)
    h: float = Field(ge=0, le=1)


class FieldString(BaseModel):
    model_config = ConfigDict(extra="forbid")
    value: Optional[str] = None
    confidence: float = Field(0.0, ge=0, le=1)
    source: str = Field("none", pattern="^(ocr|vlm|registry|none)$")


class FieldStrength(BaseModel):
    model_config = ConfigDict(extra="forbid")
    value: Optional[float] = None
    unit: Optional[str] = None
    confidence: float = Field(0.0, ge=0, le=1)
    source: str = Field("none", pattern="^(ocr|vlm|registry|none)$")


class Blur(BaseModel):
    model_config = ConfigDict(extra="forbid")
    score: float = Field(0.0, ge=0, le=1)
    is_blurry: bool = False


class Exposure(BaseModel):
    model_config = ConfigDict(extra="forbid")
    score: float = Field(0.0, ge=0, le=1)
    too_dark: bool = False
    too_bright: bool = False


class Glare(BaseModel):
    model_config = ConfigDict(extra="forbid")
    score: float = Field(0.0, ge=0, le=1)
    has_glare: bool = False


class FrameQuality(BaseModel):
    model_config = ConfigDict(extra="forbid")
    acceptable: bool
    score: float = Field(0.0, ge=0, le=1)
    blur: Optional[Blur] = None
    exposure: Optional[Exposure] = None
    glare: Optional[Glare] = None
    guidance: List[str] = Field(default_factory=list)


class Bottle(BaseModel):
    model_config = ConfigDict(extra="forbid")
    detected: bool
    confidence: float = Field(0.0, ge=0, le=1)
    bbox: Optional[BBox] = None


class Label(BaseModel):
    model_config = ConfigDict(extra="forbid")
    detected: bool
    confidence: float = Field(0.0, ge=0, le=1)
    bbox: Optional[BBox] = None
    text: Optional[str] = None


class Medication(BaseModel):
    model_config = ConfigDict(extra="forbid")
    name: FieldString = Field(default_factory=FieldString)
    strength: Optional[FieldStrength] = None
    form: Optional[FieldString] = None
    manufacturer: Optional[FieldString] = None


class InstructionItem(BaseModel):
    model_config = ConfigDict(extra="forbid")
    kind: str = Field(pattern="^(dose|frequency|route|duration|warning|other)$")
    text: str


class DoseInfo(BaseModel):
    """v1.1 additive: structured per-dose quantity as written on the label.

    Never a package count. Consumers may ignore this object; the API also uses it
    to feed the backend's ``POST /scans`` quantity field.
    """

    model_config = ConfigDict(extra="forbid")
    quantity: Optional[float] = Field(None, gt=0)
    unit: Optional[str] = None
    confidence: float = Field(0.0, ge=0, le=1)
    source: str = Field("none", pattern="^(ocr|vlm|registry|none)$")


class Instructions(BaseModel):
    model_config = ConfigDict(extra="forbid")
    raw_text: Optional[str] = None
    parsed: List[InstructionItem] = Field(default_factory=list)
    dose: Optional[DoseInfo] = None


class CandidateStrength(BaseModel):
    model_config = ConfigDict(extra="forbid")
    value: Optional[float] = None
    unit: Optional[str] = None


class Candidate(BaseModel):
    model_config = ConfigDict(extra="forbid")
    name: str
    strength: Optional[CandidateStrength] = None
    score: float = Field(0.0, ge=0, le=1)
    source: str = Field("registry", pattern="^(registry|ocr|vlm)$")


class Interpretation(BaseModel):
    model_config = ConfigDict(extra="forbid")
    available: bool = False
    summary: Optional[str] = None
    source: Optional[str] = Field(None, pattern="^(vlm)$")
    model: Optional[str] = None


class Uncertainty(BaseModel):
    model_config = ConfigDict(extra="forbid")
    level: str = Field("high", pattern="^(low|medium|high)$")
    reasons: List[str] = Field(default_factory=list)
    rescan_required: bool = False


class Timing(BaseModel):
    model_config = ConfigDict(extra="forbid")
    total_ms: float = Field(0.0, ge=0)
    stages: Dict[str, float] = Field(default_factory=dict)


class Safety(BaseModel):
    model_config = ConfigDict(extra="forbid")
    disclaimer: str = SAFETY_DISCLAIMER
    ingestion_not_inferred: bool = True
    backend_authoritative: bool = True


class ErrorInfo(BaseModel):
    model_config = ConfigDict(extra="forbid")
    code: str
    message: str
    detail: Optional[Any] = None


class PerFrameResult(BaseModel):
    """One frame's outcome inside a multi-frame label capture (v1.2 additive)."""

    model_config = ConfigDict(extra="forbid")
    index: int = Field(ge=0)
    status: str = Field(pattern="^(accepted|needs_rescan|no_medication_found|error)$")
    label_detected: Optional[bool] = None
    label_confidence: Optional[float] = Field(None, ge=0, le=1)
    clipped: Optional[bool] = None
    guidance: Optional[List[str]] = None


class CaptureInfo(BaseModel):
    """Frame accounting for multi-frame label capture (v1.2 additive)."""

    model_config = ConfigDict(extra="forbid")
    frames_requested: int = Field(ge=1, le=12)
    frames_used: int = Field(ge=0, le=12)
    fusion: str = Field("single", pattern="^(single|multi_frame)$")
    per_frame: List[PerFrameResult] = Field(default_factory=list)


class LabelMeta(BaseModel):
    """v1.3 additive: pharmacy-label metadata printed on real labels.

    Values are strings exactly as read (or derived for ``schedule_times``); absent
    values stay ``None`` with ``source="none"`` and are never fabricated.
    """

    model_config = ConfigDict(extra="forbid")
    quantity_start: Optional[FieldString] = None
    refills_remaining: Optional[FieldString] = None
    pharmacy_name: Optional[FieldString] = None
    pharmacy_phone: Optional[FieldString] = None
    prescriber: Optional[FieldString] = None
    schedule_times: Optional[FieldString] = None


class ScanResponse(BaseModel):
    """The single integration surface between inference and iOS/backend."""

    model_config = ConfigDict(extra="forbid")

    contract_version: str = CONTRACT_VERSION
    request_id: str
    status: str = Field(pattern="^(ok|needs_rescan|uncertain|no_medication_found|error)$")
    mode: str = Field(pattern="^(mock|real)$")

    frame_quality: FrameQuality
    bottle: Bottle
    label: Label
    medication: Medication
    instructions: Instructions
    candidates: List[Candidate] = Field(default_factory=list)
    interpretation: Interpretation = Field(default_factory=Interpretation)
    uncertainty: Uncertainty
    timing: Timing
    safety: Safety = Field(default_factory=Safety)
    error: Optional[ErrorInfo] = None
    capture: Optional[CaptureInfo] = None
    label_meta: Optional[LabelMeta] = None


class HealthResponse(BaseModel):
    model_config = ConfigDict(extra="forbid")
    status: str = "ok"
    service: str = "medcheck-inference"
    version: str
    uptime_s: float


class ReadyResponse(BaseModel):
    model_config = ConfigDict(extra="forbid")
    ready: bool
    mode: str = "mock"
    components: Dict[str, Any] = Field(default_factory=dict)
    reasons: List[str] = Field(default_factory=list)
